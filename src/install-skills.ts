/**
 * bezel — `install-skills`: write the Bezel agent skill into a repository.
 *
 * Coding agents (Claude Code, Codex, Cursor) load a `SKILL.md` whose description
 * matches the task at hand, and read `AGENTS.md` on every session. This installs
 * both: the skill folder under `.claude/skills/bezel/` and/or `.agents/skills/bezel/`,
 * and a marked block in `AGENTS.md` with the short rules. Files are only rewritten
 * when their content differs, existing files are backed up once before the first
 * overwrite, and nothing is ever deleted.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises"
import { dirname, join, relative, resolve } from "node:path"
import { AGENT_SKILL } from "./agent-skill"
import { mergeManagedBlock } from "./managed-block"

export const SKILL_CLIENTS = ["claude-code", "codex", "cursor", "all"] as const
export type SkillClient = (typeof SKILL_CLIENTS)[number]

/** Opening marker for the Bezel-managed block in `AGENTS.md`. */
export const AGENTS_MD_START = "<!-- bezel:start (generated by bezel install-skills — do not edit) -->"
/** Closing marker for the Bezel-managed block in `AGENTS.md`. */
export const AGENTS_MD_END = "<!-- bezel:end -->"

const CLAUDE_SKILLS_DIR = ".claude/skills"
const AGENTS_SKILLS_DIR = ".agents/skills"

export interface InstallSkillsOptions {
  /** Repository root the files are written under. Default: `process.cwd()`. */
  cwd?: string
  /** Which agent's skill folder(s) to write. */
  client: SkillClient
  /** Also maintain the managed block in `AGENTS.md`. Default: `true`. */
  agentsMd?: boolean
}

export interface InstallSkillsResult {
  /** Files created or updated, relative to `cwd`. */
  written: string[]
  /** Files that already had the right content, relative to `cwd`. */
  unchanged: string[]
  /** Files backed up to `<path>.bezel-backup` before being overwritten, relative to `cwd`. */
  backedUp: string[]
  /** Follow-up notes for the user (for example a `CLAUDE.md` that does not include `AGENTS.md`). */
  hints: string[]
}

/** Skill folders a client reads, relative to the repo root. */
export function skillDirectories(client: SkillClient): string[] {
  if (client === "claude-code") return [CLAUDE_SKILLS_DIR]
  if (client === "codex" || client === "cursor") return [AGENTS_SKILLS_DIR]
  return [CLAUDE_SKILLS_DIR, AGENTS_SKILLS_DIR]
}

/** Merge the Bezel block into existing `AGENTS.md` contents. */
export function mergeAgentsMd(existing: string): string {
  return mergeManagedBlock(existing, AGENT_SKILL.agentsMdBlock.split("\n"), {
    start: AGENTS_MD_START,
    end: AGENTS_MD_END,
  })
}

async function readIfExists(path: string): Promise<string | undefined> {
  try {
    return await readFile(path, "utf8")
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return undefined
    throw error
  }
}

/**
 * Write `content` to `path` only when it differs from what is there. An existing file
 * is copied to `<path>.bezel-backup` the first time it is overwritten (the backup is
 * never replaced, so the user's original survives repeated runs).
 */
async function writeManaged(
  cwd: string,
  path: string,
  content: string,
  result: InstallSkillsResult,
): Promise<void> {
  const rel = relative(cwd, path)
  const existing = await readIfExists(path)
  if (existing === content) {
    result.unchanged.push(rel)
    return
  }
  await mkdir(dirname(path), { recursive: true })
  if (existing !== undefined) {
    try {
      await writeFile(`${path}.bezel-backup`, existing, { flag: "wx", mode: 0o600 })
      result.backedUp.push(rel)
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "EEXIST") throw error
    }
  }
  await writeFile(path, content, "utf8")
  result.written.push(rel)
}

/** Install the Bezel skill (and the `AGENTS.md` block) into a repository. */
export async function installSkills(options: InstallSkillsOptions): Promise<InstallSkillsResult> {
  const cwd = resolve(options.cwd ?? process.cwd())
  const result: InstallSkillsResult = { written: [], unchanged: [], backedUp: [], hints: [] }

  for (const dir of skillDirectories(options.client)) {
    for (const [file, content] of Object.entries(AGENT_SKILL.files)) {
      await writeManaged(cwd, join(cwd, dir, AGENT_SKILL.name, file), content, result)
    }
  }

  if (options.agentsMd ?? true) {
    const agentsPath = join(cwd, "AGENTS.md")
    const existing = (await readIfExists(agentsPath)) ?? ""
    const merged = mergeAgentsMd(existing)
    if (merged === existing) {
      result.unchanged.push("AGENTS.md")
    } else {
      await writeFile(agentsPath, merged, "utf8")
      result.written.push("AGENTS.md")
    }

    const claudeMd = await readIfExists(join(cwd, "CLAUDE.md"))
    if (claudeMd !== undefined && !claudeMd.includes("@AGENTS.md")) {
      result.hints.push(
        "CLAUDE.md exists and does not include AGENTS.md. Add a line containing `@AGENTS.md` to CLAUDE.md so Claude Code loads the Bezel rules.",
      )
    }
  }

  return result
}

/** Map an `install-mcp` client to the skill folders it reads. */
export function skillClientForMcpClient(client: string): SkillClient {
  if (client === "claude-code" || client === "codex" || client === "cursor") return client
  return "all"
}

/**
 * The `bezel install-skills` command: pick a client (flag or interactive menu),
 * install, and report what changed.
 */
export async function installSkillsCommand(
  clientName: string | undefined,
  options: { agentsMd?: boolean; cwd?: string } = {},
): Promise<void> {
  let choice = clientName
  if (!choice) {
    if (!process.stdin.isTTY) {
      throw new Error(`Choose a client with --client ${SKILL_CLIENTS.join("|")}.`)
    }
    const { default: select } = await import("@inquirer/select")
    try {
      choice = await select<SkillClient>({
        message: "Install the Bezel skill for:",
        choices: [
          { name: "Claude Code (.claude/skills)", value: "claude-code" },
          { name: "Codex (.agents/skills)", value: "codex" },
          { name: "Cursor (.agents/skills)", value: "cursor" },
          { name: "All of the above", value: "all" },
        ],
      })
    } catch (error) {
      if (error instanceof Error && error.name === "ExitPromptError") {
        console.log("Setup cancelled.")
        return
      }
      throw error
    }
  }
  if (!SKILL_CLIENTS.includes(choice as SkillClient))
    throw new Error(`Unknown client: ${choice}. Choose ${SKILL_CLIENTS.join(", ")}.`)

  const result = await installSkills({
    cwd: options.cwd,
    client: choice as SkillClient,
    agentsMd: options.agentsMd,
  })
  reportInstallSkills(result)
}

/** Print an {@link InstallSkillsResult} the way the CLI does. */
export function reportInstallSkills(result: InstallSkillsResult): void {
  for (const file of result.written) console.log(`Bezel skill: wrote ${file}`)
  for (const file of result.backedUp) console.log(`Bezel skill: backed up ${file}.bezel-backup`)
  if (result.written.length === 0) console.log("Bezel skill: already up to date.")
  for (const hint of result.hints) console.log(`Note: ${hint}`)
  console.log(
    "Next: open this repo in your assistant. The Bezel skill loads automatically when a task touches design tokens.",
  )
}
